#!/usr/bin/env bash
# install-server-unit.sh [--check] — install scripts/systemd/claudecodeui-server.service as a fixed
# systemd user unit, plus the per-host drop-in with this checkout's WorkingDirectory and log path.
#
# It never writes ~/.config/environment.d: node/claude are USER-scope settings that the user owns
# (995-nvm-node.conf). It only READS the user manager's environment and refuses to install when
# that environment would make the server resolve the wrong node, or carries plugin bin dirs.
# Everything that can refuse happens before anything is written.
#
#   --check   preflight only; writes nothing
#
# Test seams: QUAY_SERVER_UNIT (default claudecodeui-server), QUAY_SERVER_LOG,
#             QUAY_UNIT_DIR (default ~/.config/systemd/user).
# Re-run after a node upgrade? No — node is not in the unit. Update 995-nvm-node.conf and
# `systemctl --user daemon-reload`, then restart the server.
set -eu

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
UNIT="${QUAY_SERVER_UNIT:-claudecodeui-server}"
LOG_FILE="${QUAY_SERVER_LOG:-$ROOT_DIR/server.log}"
UNIT_DIR="${QUAY_UNIT_DIR:-$HOME/.config/systemd/user}"
TEMPLATE="$ROOT_DIR/scripts/systemd/claudecodeui-server.service"
CHECK=no
case "${1:-}" in
  --check) CHECK=yes ;;
  "") ;;
  *) echo "usage: install-server-unit.sh [--check]" >&2; exit 2 ;;
esac

die() { echo "install-server-unit: REFUSED: $*" >&2; exit 1; }

[ -f "$TEMPLATE" ] || die "$TEMPLATE is missing"
command -v systemctl >/dev/null 2>&1 || die "no systemctl"
systemctl --user show-environment >/dev/null 2>&1 || die "no usable systemd user manager"

MGR_PATH="$(systemctl --user show-environment | sed -n 's/^PATH=//p' | head -1)"
[ -n "$MGR_PATH" ] || die "the user manager has no PATH"
case "$MGR_PATH" in
  *plugins/cache*|*plugins/synced*)
    die "the user manager PATH carries plugin bin dirs ($MGR_PATH); something ran 'systemctl --user set-environment/import-environment PATH' — fix that, do not install" ;;
esac
case ":$MGR_PATH:" in
  *":$HOME/.local/bin:"*) ;;
  *) die "the user manager PATH has no $HOME/.local/bin (claude-* launchers, gh, go live there; the quay worker driver dies with 'spawn claude-fjdac ENOENT' without it); add it to ~/.config/environment.d/995-nvm-node.conf, then 'systemctl --user daemon-reload'" ;;
esac
NODE="$(PATH="$MGR_PATH" command -v node || true)"
[ -n "$NODE" ] || die "no node on the user manager PATH ($MGR_PATH); set it in ~/.config/environment.d/995-nvm-node.conf then 'systemctl --user daemon-reload'"
case "$(readlink -f "$NODE")" in
  /usr/bin/*|/bin/*) die "node resolves to the system node ($NODE); put the nvm bin first in ~/.config/environment.d/995-nvm-node.conf (file name must sort after 99-environment.conf), then 'systemctl --user daemon-reload'" ;;
esac
CLAUDE_ENV="$(systemctl --user show-environment | sed -n 's/^CLAUDE_CLI_PATH=//p' | head -1)"
if [ -n "$CLAUDE_ENV" ]; then
  [ -x "$CLAUDE_ENV" ] || die "CLAUDE_CLI_PATH=$CLAUDE_ENV in the user manager is not executable"
else
  PATH="$MGR_PATH" command -v claude >/dev/null || die "no claude on the user manager PATH and no CLAUDE_CLI_PATH"
fi
[ -f "$ROOT_DIR/dist-server/server/index.js" ] || die "dist-server/server/index.js is missing — run the build first (npm run server does not build)"

echo "preflight OK: node=$NODE claude=${CLAUDE_ENV:-<on PATH>} manager PATH=$MGR_PATH"
[ "$CHECK" = yes ] && exit 0

mkdir -p "$UNIT_DIR/$UNIT.service.d"
install -m 0644 "$TEMPLATE" "$UNIT_DIR/$UNIT.service"
cat >"$UNIT_DIR/$UNIT.service.d/10-paths.conf" <<DROPIN
# Generated by scripts/install-server-unit.sh — this checkout's paths. Re-run it if the checkout moves.
[Service]
WorkingDirectory=$ROOT_DIR
StandardOutput=append:$LOG_FILE
StandardError=append:$LOG_FILE
DROPIN
systemd-analyze --user verify "$UNIT_DIR/$UNIT.service" 2>&1 | grep -v '^$' || true
systemctl --user daemon-reload
echo "installed $UNIT_DIR/$UNIT.service (+ .d/10-paths.conf). A same-named transient unit that is still running keeps"
echo "precedence until it is stopped: use scripts/restart-server-detached.sh for the switch."
