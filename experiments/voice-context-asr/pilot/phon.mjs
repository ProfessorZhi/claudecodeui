// D1: sound-alike × vocabulary re-scoring over a recogniser's text. Pure functions; pilot-grade
// (the pronunciation dictionary is loaded from a scratch npm dir, see DICT_DIR).
import { createRequire } from 'node:module';
const DICT_DIR = '/tmp/vk/npm/node_modules/';
const req = createRequire(DICT_DIR);
const { dictionary } = await import(req.resolve('cmu-pronouncing-dictionary'));
const { doubleMetaphone } = await import(req.resolve('double-metaphone'));

export const W = { sound: 0.45, project: 0.25, recent: 0.2, history: 0.1 };   // frozen in PREREG-v2
export const TEMP = 0.1;           // softmax temperature turning scores into the displayed probabilities
export const MIN_SIM = 0.75;       // a window must sound at least this much like a term to be a candidate
const LETTERS = { A: 'EY', B: 'B IY', C: 'S IY', D: 'D IY', E: 'IY', F: 'EH F', G: 'JH IY', H: 'EY CH', I: 'AY', J: 'JH EY', K: 'K EY', L: 'EH L', M: 'EH M', N: 'EH N', O: 'OW', P: 'P IY', Q: 'K Y UW', R: 'AA R', S: 'EH S', T: 'T IY', U: 'Y UW', V: 'V IY', W: 'D AH B AH L Y UW', X: 'EH K S', Y: 'W AY', Z: 'Z IY' };
const DIGITS = ['zero', 'one', 'two', 'three', 'four', 'five', 'six', 'seven', 'eight', 'nine'];
// hand-given pronunciations for project words the dictionary lacks (in production: generated by a g2p at index time)
const MANUAL = { cantus: 'K AE N T AH S', cli: 'K L AY' , zrok: 'Z R AA K', tmux: 'T IY M AH K S', quay: 'K IY' };
const strip = (p) => p.replace(/\d/g, '');
const own = (o, k) => (Object.hasOwn(o, k) ? o[k] : undefined);   // 'constructor', 'toString'… are real words in a project
export const wordPron = (w) => { const l = w.toLowerCase(); const p = own(MANUAL, l) ?? own(dictionary, l); return p ? strip(p).split(' ') : null; };
function termPron(term) {
  const out = [];
  for (const part of term.split(/[-_./]|(?<=[a-z])(?=[A-Z])/).filter(Boolean)) {
    if (/^\d+$/.test(part)) { for (const d of part) out.push(...strip(own(dictionary, DIGITS[+d])).split(' ')); continue; }
    const p = wordPron(part);
    if (p) { out.push(...p); continue; }
    if (/^[A-Za-z]{1,4}$/.test(part) && part === part.toUpperCase()) { for (const ch of part) out.push(...LETTERS[ch].split(' ')); continue; }
    if (part === 'archguard') { out.push(...wordPron('arch'), ...wordPron('guard')); continue; }
    return null;
  }
  return out;
}
const VOWELS = new Set('AA AE AH AO AW AY EH ER EY IH IY OW OY UH UW'.split(' '));
const VOICE = [['P', 'B'], ['T', 'D'], ['K', 'G'], ['F', 'V'], ['S', 'Z'], ['CH', 'JH'], ['TH', 'DH'], ['SH', 'ZH']];
const subCost = (a, b) => {
  if (a === b) return 0;
  if (VOWELS.has(a) && VOWELS.has(b)) return 0.4;
  if (VOICE.some(([x, y]) => (a === x && b === y) || (a === y && b === x))) return 0.4;
  if (new Set(['W', 'R', 'L', 'Y']).has(a) && new Set(['W', 'R', 'L', 'Y']).has(b)) return 0.6;
  return 1;
};
function weightedEdit(a, b) {
  const d = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 0; j <= b.length; j++) d[0][j] = j;
  for (let i = 1; i <= a.length; i++) for (let j = 1; j <= b.length; j++) d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + subCost(a[i - 1], b[j - 1]));
  return d[a.length][b.length];
}
const phonemeSim = (a, b) => (a && b ? 1 - weightedEdit(a, b) / Math.max(a.length, b.length) : 0);
const skel = (s) => doubleMetaphone(s.replace(/[^A-Za-z]/g, ''))[0] ?? '';
function lev(a, b) { const d = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]); for (let j = 0; j <= b.length; j++) d[0][j] = j; for (let i = 1; i <= a.length; i++) for (let j = 1; j <= b.length; j++) d[i][j] = Math.min(d[i - 1][j] + 1, d[i][j - 1] + 1, d[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1)); return d[a.length][b.length]; }
function skelSim(a, b) { if (!a || !b) return 0; const s = 1 - lev(a, b) / Math.max(a.length, b.length); return s * (Math.min(a.length, b.length) >= 3 ? 0.9 : 0.6); }
export const sound = (windowText, term, termP, termS) => {
  const wp = windowText.split(/\s+/).map(wordPron);
  const p = wp.every(Boolean) ? wp.flat() : null;
  return Math.max(phonemeSim(p, termP), skelSim(skel(windowText), termS));
};
/** vocab: [{ term, recent: bool }]  — every entry is a project term; `recent` marks the conversation's own words. */
export function indexVocab(vocab) { return vocab.map((v) => ({ ...v, pron: termPron(v.term), skel: skel(v.term) })); }
const normKey = (s) => s.toLowerCase().replace(/[^a-z0-9]/g, '');
const softmax = (xs) => { const m = Math.max(...xs); const e = xs.map((x) => Math.exp((x - m) / TEMP)); const z = e.reduce((a, b) => a + b, 0); return e.map((v) => v / z); };
/** Returns spans: { start, end, text, candidates: [[word, p], ...] } — the original window is always one candidate. */
export function analyse(text, index, { minSim = MIN_SIM, history = {} } = {}) {
  const toks = [...text.matchAll(/[A-Za-z']+/g)].map((m) => ({ s: m.index, e: m.index + m[0].length, w: m[0] }));
  const wins = [];
  for (let i = 0; i < toks.length; i++) for (let n = 1; n <= 4 && i + n <= toks.length; n++) {
    const parts = toks.slice(i, i + n);
    if (n > 1 && parts.some((t, k) => k > 0 && /[^\sA-Za-z']/.test(text.slice(parts[k - 1].e, t.s)))) break;   // only whitespace between words
    wins.push({ s: parts[0].s, e: parts[n - 1].e, text: text.slice(parts[0].s, parts[n - 1].e), n });
  }
  const spans = [];
  for (const w of wins) {
    const cands = [];
    for (const v of index) {
      if (normKey(w.text) === normKey(v.term)) { if (w.text !== v.term) cands.push({ term: v.term, sim: 1, v }); continue; }   // shape / case repair
      const sim = sound(w.text, v.term, v.pron, v.skel);
      if (sim >= minSim) cands.push({ term: v.term, sim, v });
    }
    if (!cands.length) continue;
    const common = w.text.split(/\s+/).every((x) => own(dictionary, x.toLowerCase())) ? 1 : 0;
    const scored = cands.map((c) => ({ word: c.term, sc: W.sound * c.sim + W.project + W.recent * (c.v.recent ? 1 : 0) + W.history * Math.min(1, (history[c.term] ?? 0) / 5), sim: c.sim }));
    const incumbent = { word: w.text, sc: W.sound * 1 + W.project * common, sim: 1 };
    const all = [incumbent, ...scored.sort((a, b) => b.sc - a.sc)];
    const probs = softmax(all.map((x) => x.sc));
    spans.push({ start: w.s, end: w.e, text: w.text, n: w.n, candidates: all.map((x, i) => [x.word, +probs[i].toFixed(3)]).sort((a, b) => b[1] - a[1]), sims: Object.fromEntries(all.map((x) => [x.word, +x.sim.toFixed(2)])) });
  }
  // keep, among overlapping windows, the one whose top candidate is strongest; prefer longer on ties
  const isRep = (x) => (x.candidates[0][0] !== x.text ? 1 : 0);
  spans.sort((a, b) => isRep(b) - isRep(a) || b.candidates[0][1] - a.candidates[0][1] || b.n - a.n);
  const kept = [];
  for (const s of spans) if (!kept.some((k) => s.start < k.end && k.start < s.end)) kept.push(s);
  return kept.sort((a, b) => a.start - b.start);
}
/** Applies each span's top candidate when it is not the original and its probability reaches tau. */
export function applyReplacements(text, spans, tau) {
  let out = text; const reps = [];
  for (const s of [...spans].sort((a, b) => b.start - a.start)) {
    const [word, p] = s.candidates[0];
    if (word !== s.text && p >= tau) { out = out.slice(0, s.start) + word + out.slice(s.end); reps.push([s.text, word, p]); }
  }
  return { text: out, reps };
}
