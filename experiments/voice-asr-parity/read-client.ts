/**
 * AC-130's client half: the two hops the browser originates, plus the client half of the
 * response-tolerance reading — all three driven on the SHIPPED code.
 *
 *   npx tsx --tsconfig tsconfig.json experiments/voice-asr-parity/read-client.ts
 *
 * What it drives, and nothing else:
 *
 *   direct-outbound     `transcribeVoice` with a base URL configured  -> the request the browser
 *                       sends to the user's own recogniser
 *   inbound             `transcribeVoice` with no base URL configured -> the request the browser
 *                       sends to the CloudCLI proxy (`/api/voice/transcribe`)
 *   response-tolerance  `parseTranscriptionResponse` on a handful of response bodies, so the
 *                       direct path's strictness is a reading rather than a claim
 *
 * The reader does exactly three things: install doubles for the two globals the shipping code
 * reaches for (`fetch`, `window`/`localStorage`), call the shipped symbols, and serialize what it
 * observed. It does not assemble a multipart body and it does not parse a transcription response —
 * both are what the symbols under test are for, and a reader that did them itself would be a
 * reading of the reader.
 *
 * Two readers rather than one because the two halves cannot share a process: the root tsconfig
 * maps `@/*` to `src/*` and the server tsconfig maps it to `server/*`, so the two alias tables are
 * mutually exclusive. The two consumer sets are split the same way today.
 *
 * Not covered by any tsconfig include or by `npm run lint` (see the task's S1): the probe that
 * reads these lines asserts that all four readings really arrive, so an empty or absent reader is
 * a red rather than a silent green.
 */

import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';

import { parseTranscriptionResponse, transcribeVoice } from '@/shared/api';
import { resetVoiceConfig, updateVoiceConfig } from '@/shared/voiceConfig';

/** The marker every reading line starts with. The probe reads exactly these lines. */
const MARKER = 'ASR-PARITY-READING ';
/** The marker of the one fixture line, so the probe can tie the baseline back to this constant. */
const FIXTURE_MARKER = 'ASR-PARITY-FIXTURE ';

/**
 * The synthetic audio the client readings are taken on: fixed bytes, fixed name, fixed type.
 *
 * Nothing here is read from the environment. A fixture that varied between runs would make every
 * body byte differ and the baseline could never hold, which is the same failure as a criterion
 * that can never go red — just quieter. The probe re-derives the baseline's `audio.sha256` from
 * this very declaration (AC11), so it is the one place the bytes are stated.
 */
const SYNTHETIC_AUDIO_TEXT = 'k-asr-parity-fixture-audio-0123456789abcdef';
const SYNTHETIC_AUDIO_NAME = 'clip.webm';
const SYNTHETIC_AUDIO_MIME = 'audio/webm';

/**
 * The recogniser the direct path is pointed at, and the key it authenticates with. Both are made
 * up: the hop is read off the `fetch` double, so no request leaves the process.
 */
const DIRECT_BASE_URL = 'https://asr.invalid/v1';
const READER_API_KEY = 'k-reader-key';
const READER_STT_MODEL = 'k-reader-stt';

/**
 * The token the inbound hop authenticates with. The shipping code reads it from storage, so the
 * double below supplies it; it is a constant so the header it produces is one too.
 */
const READER_TOKEN = 'k-reader-token';

/** The synthetic audio as bytes, built here so no environment value can reach it. */
function syntheticAudio(): Uint8Array {
  return new TextEncoder().encode(SYNTHETIC_AUDIO_TEXT);
}

function sha256Hex(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex');
}

type CapturedRequest = {
  url: string;
  method: string;
  headers: Array<[string, string]>;
  body: unknown;
};

/**
 * Reads the headers a call declared, sorted so the reading does not depend on insertion order.
 *
 * Only what the shipping code *set* is read, not what the platform would add: "the direct path
 * sets no Content-Type because the body is a FormData" is one of the facts this reading exists to
 * pin, and asking the encoder would replace that with a generated boundary that differs per run.
 */
function readHeaders(headers: unknown): Array<[string, string]> {
  if (!headers || typeof headers !== 'object') return [];
  const entries = Array.isArray(headers) ? headers : Object.entries(headers);
  return entries
    .map(([name, value]) => [String(name).toLowerCase(), String(value)] as [string, string])
    .sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));
}

/**
 * Normalizes a captured FormData body into a boundary-independent reading.
 *
 * The boundary is freshly generated by the platform encoder on every serialization, so comparing
 * the raw bytes would be red on the first run and on every run after it — a permanently-red
 * reading is exactly as unusable as a permanently-green one. Only the boundary is replaced; every
 * other byte (part names, filenames, part content types, the audio bytes) is kept verbatim, so a
 * renamed field or a changed part order still moves the reading.
 *
 * The encoding itself is the platform's (`Request`), not this reader's: nothing here decides what
 * a multipart body looks like. `latin1` maps byte to character one-to-one, so the text round-trips
 * exactly and the sha256 is taken over the same bytes the platform produced.
 */
async function readMultipartBody(body: FormData): Promise<Record<string, string>> {
  const encoded = new Request('http://asr.invalid/', { method: 'POST', body });
  const contentType = encoded.headers.get('content-type') ?? '';
  const boundary = /boundary=(.+)$/.exec(contentType)?.[1] ?? '';
  const bytes = Buffer.from(await encoded.arrayBuffer());
  const text = bytes.toString('latin1');
  const normalized = boundary ? text.split(boundary).join('BOUNDARY') : text;
  return {
    boundary: 'BOUNDARY',
    text: normalized,
    sha256: sha256Hex(Buffer.from(normalized, 'latin1')),
  };
}

/** The serialized form of one captured call: verb, URL, declared headers, normalized body. */
async function readCaptured(captured: CapturedRequest): Promise<Record<string, unknown>> {
  const body = captured.body;
  return {
    url: captured.url,
    method: captured.method,
    headers: captured.headers,
    body:
      body instanceof FormData
        ? { kind: 'multipart', ...(await readMultipartBody(body)) }
        : { kind: 'other', text: String(body) },
  };
}

/**
 * The window and storage the shipping code reaches for, plus the `fetch` double every reading is
 * taken off. `voiceConfigHeaders()` returns nothing at all without a `window`, so a reader that
 * skipped this would silently drop the `x-voice-*` headers and the inbound reading would be of a
 * request the app never sends.
 */
function installDoubles(calls: CapturedRequest[]): void {
  const globals = globalThis as Record<string, unknown>;

  globals.window = {
    dispatchEvent: () => true,
    addEventListener: () => undefined,
    removeEventListener: () => undefined,
  };
  globals.localStorage = {
    getItem: (key: string) => (key === 'auth-token' ? READER_TOKEN : null),
    setItem: () => undefined,
    removeItem: () => undefined,
  };

  globals.fetch = async (input: unknown, init?: Record<string, unknown>) => {
    const url = typeof input === 'string' ? input : String(input);
    const method = String(init?.method ?? 'GET').toUpperCase();

    // The settings document is read (and written back by the debounced save) over the same
    // endpoint the app uses; it is the shipping config module's own path, not a reading.
    if (url === '/api/voice/config') {
      return new Response(
        JSON.stringify({
          baseUrl: DIRECT_BASE_URL,
          apiKey: READER_API_KEY,
          sttModel: READER_STT_MODEL,
          ttsModel: '',
          ttsVoice: '',
          ttsFormat: '',
        }),
        { status: 200, headers: { 'Content-Type': 'application/json' } },
      );
    }

    calls.push({
      url,
      method,
      headers: readHeaders(init?.headers),
      body: init?.body,
    });
    return new Response(JSON.stringify({ text: 'k-asr-answer' }), { status: 200 });
  };
}

/** The one call that matches `predicate`, or a loud failure — a reading of nothing is not a reading. */
function takeCaptured(
  calls: CapturedRequest[],
  predicate: (call: CapturedRequest) => boolean,
  label: string,
): CapturedRequest {
  const matches = calls.filter(predicate);
  if (matches.length !== 1) {
    throw new Error(`${label}: expected exactly one captured request, saw ${matches.length}`);
  }
  return matches[0];
}

/**
 * The absolute path of the shipping module the reading was taken on, resolved by the loader
 * (`import.meta.resolve` goes through the same alias table the imports above used) rather than
 * spelled out here: a declared path would keep printing an old location after a move, which is
 * precisely the move `--explain-sites` exists to make visible.
 */
function siteOf(specifier: string): string {
  return fileURLToPath(import.meta.resolve(specifier));
}

function emitFixture(): void {
  const bytes = syntheticAudio();
  process.stdout.write(
    FIXTURE_MARKER +
      JSON.stringify({
        source: 'synthetic',
        name: SYNTHETIC_AUDIO_NAME,
        mimeType: SYNTHETIC_AUDIO_MIME,
        bytes: bytes.length,
        sha256: sha256Hex(bytes),
      }) +
      '\n',
  );
}

function emit(line: Record<string, unknown>): void {
  process.stdout.write(MARKER + JSON.stringify(line) + '\n');
}

/** One response-tolerance case: the body handed to the parse, and what the parse made of it. */
async function toleranceCase(name: string, body: string): Promise<Record<string, unknown>> {
  try {
    const text = await parseTranscriptionResponse(new Response(body, { status: 200 }));
    return { name, outcome: 'value', text };
  } catch {
    return { name, outcome: 'throws' };
  }
}

async function main(): Promise<void> {
  const calls: CapturedRequest[] = [];
  installDoubles(calls);

  const apiSite = siteOf('@/shared/api');
  const audio = new Blob([syntheticAudio()], { type: SYNTHETIC_AUDIO_MIME });

  // Direct first, on the settings the double serves: `transcribeVoice` hydrates the config itself
  // on the first call, waiting on `whenVoiceConfigReady()` exactly as the hook does.
  await transcribeVoice(audio, SYNTHETIC_AUDIO_NAME);
  const direct = takeCaptured(
    calls,
    (call) => call.url.startsWith(`${DIRECT_BASE_URL}/`),
    'direct-outbound',
  );
  emit({
    group: 'direct-outbound',
    site: { symbol: 'transcribeVoice', file: apiSite },
    value: await readCaptured(direct),
  });

  // The proxy branch is the same symbol with the base URL cleared — the shipped setter the
  // settings tab uses, so the branch is chosen by the app's own code path and not by a stub.
  updateVoiceConfig({ baseUrl: '' });
  await transcribeVoice(audio, SYNTHETIC_AUDIO_NAME);
  const inbound = takeCaptured(
    calls,
    (call) => call.url === '/api/voice/transcribe',
    'inbound',
  );
  emit({
    group: 'inbound',
    site: { symbol: 'transcribeVoice', file: apiSite },
    value: await readCaptured(inbound),
  });

  emit({
    group: 'response-tolerance',
    half: 'direct',
    site: { symbol: 'parseTranscriptionResponse', file: apiSite },
    value: {
      // A JSON body is the positive control: a parse that only ever threw would satisfy "non-JSON
      // throws" while being useless, and the two numeric/absent cases pin the exact expression
      // (`|| ''`, not `?? ''`) the direct path has always used.
      cases: [
        await toleranceCase('non-json-body', 'k-asr-not-json'),
        await toleranceCase('json-text', JSON.stringify({ text: 'k-asr-answer' })),
        await toleranceCase('json-numeric-text', JSON.stringify({ text: 0 })),
        await toleranceCase('json-without-text', JSON.stringify({ other: 'k-asr-answer' })),
        await toleranceCase('json-null', 'null'),
      ],
    },
  });

  emitFixture();

  // Drops the debounced settings write the setter above scheduled, so the process can end.
  resetVoiceConfig();
}

main().catch((error: unknown) => {
  process.stderr.write(`read-client: ${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
